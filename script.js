document.addEventListener("DOMContentLoaded", () => {
    // --- Language Switch Logic ---
    const langSelector = document.getElementById("language-selector");
    
    function setLanguage(lang) {
        // Fallback to English if language dictionary is not fully defined
        const activeLangDict = translations[lang] || translations['en'];
        const fallbackDict = translations['en'];

        // Update all text elements
        const elements = document.querySelectorAll("[data-i18n]");
        elements.forEach(el => {
            const key = el.getAttribute("data-i18n");
            // Prefer the selected language, fallback to English if key is missing
            if (activeLangDict[key]) {
                el.innerText = activeLangDict[key];
            } else if (fallbackDict[key]) {
                el.innerText = fallbackDict[key];
            }
        });
        
        // Update input placeholder separately
        const chatInput = document.getElementById("chat-input");
        if (chatInput) {
            chatInput.placeholder = activeLangDict["input_placeholder"] || fallbackDict["input_placeholder"];
        }
    }

    // Set default language
    setLanguage('en');

    if (langSelector) {
        langSelector.addEventListener("change", (e) => {
            const lang = e.target.value;
            setLanguage(lang);
        });
    }

    // --- View Toggling Logic ---
    const navDashboard = document.getElementById("nav-dashboard");
    const navChat = document.getElementById("nav-chat");
    const viewDashboard = document.getElementById("dashboard-view");
    const viewChat = document.getElementById("chat-view");
    const viewAnimalDetails = document.getElementById("animal-details-view");
    const viewMyCrops = document.getElementById("my-crops-view");
    const viewMyLivestock = document.getElementById("my-livestock-view");
    const viewDiseaseDetection = document.getElementById("disease-detection-view");
    
    const floatBtnIcon = document.getElementById("float-btn-icon");
    const mainFloatBtn = document.getElementById("main-float-btn");
    const floatingMicContainer = document.querySelector(".floating-mic");

    function hideAllViews() {
        if(viewDashboard) viewDashboard.style.display = "none";
        if(viewChat) viewChat.style.display = "none";
        if(viewAnimalDetails) viewAnimalDetails.style.display = "none";
        if(viewMyCrops) viewMyCrops.style.display = "none";
        if(viewMyLivestock) viewMyLivestock.style.display = "none";
        if(viewDiseaseDetection) viewDiseaseDetection.style.display = "none";
        if(floatingMicContainer) floatingMicContainer.style.display = "block"; // Default show
        
        // Remove active class from nav items by default
        navDashboard.classList.remove("active");
        navChat.classList.remove("active");
    }

    // Global navigation function
    window.navigateTo = function(viewId) {
        hideAllViews();
        const targetView = document.getElementById(viewId);
        if(targetView) {
            targetView.style.display = "block";
        }
        
        // Handle floating mic and nav states
        if (viewId === 'dashboard-view') {
            navDashboard.classList.add("active");
            floatBtnIcon.className = "fa-regular fa-message";
        } else if (viewId === 'chat-view') {
            navChat.classList.add("active");
            floatBtnIcon.className = "fa-solid fa-microphone";
        } else {
            // Inner views hide the floating mic
            if(floatingMicContainer) floatingMicContainer.style.display = "none";
        }
    };

    navDashboard.addEventListener("click", () => {
        window.navigateTo('dashboard-view');
    });

    navChat.addEventListener("click", () => {
        window.navigateTo('chat-view');
    });

    // --- Animal Details View Logic ---
    const livestockItems = document.querySelectorAll(".livestock-item");
    const backToDashBtn = document.getElementById("back-to-dash-btn");

    livestockItems.forEach(item => {
        item.addEventListener("click", () => {
            window.navigateTo('animal-details-view');
        });
    });

    if (backToDashBtn) {
        backToDashBtn.addEventListener("click", () => {
            window.navigateTo('my-livestock-view'); // Go back to livestock list instead of dash
        });
    }

    // --- Tabs Logic in Details View ---
    const detailTabs = document.querySelectorAll(".details-tabs .tab");
    const tabContents = document.querySelectorAll("#animal-details-view .tab-content");

    detailTabs.forEach(tab => {
        tab.addEventListener("click", () => {
            const target = tab.getAttribute("data-tab");
            
            // Remove active from all tabs & contents
            detailTabs.forEach(t => t.classList.remove("active"));
            tabContents.forEach(c => c.style.display = "none");
            
            // Add active to clicked tab
            tab.classList.add("active");
            document.getElementById("tab-" + target).style.display = "block";
        });
    });

    // Also allow opening chat from the floating message icon if in dashboard mode
    mainFloatBtn.addEventListener("click", () => {
        if (viewDashboard.style.display !== "none") {
            // Switch to chat view
            navChat.click();
        } else {
            console.log("Mic activated - listening...");
        }
    });

    // --- Side Drawer Logic ---
    const openMenuBtn = document.getElementById("open-menu-btn");
    const closeMenuBtn = document.getElementById("close-menu-btn");
    const sideDrawer = document.getElementById("side-drawer");
    const sideOverlay = document.getElementById("side-menu-overlay");

    function openDrawer() {
        sideDrawer.classList.add("active");
        sideOverlay.classList.add("active");
    }

    function closeDrawer() {
        sideDrawer.classList.remove("active");
        sideOverlay.classList.remove("active");
    }

    if(openMenuBtn) openMenuBtn.addEventListener("click", openDrawer);
    if(closeMenuBtn) closeMenuBtn.addEventListener("click", closeDrawer);
    if(sideOverlay) sideOverlay.addEventListener("click", closeDrawer);

});
